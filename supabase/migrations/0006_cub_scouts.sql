  add constraint advancement_items_kind_check check (kind in ('rank','badge','adventure'));

alter table public.advancement_items
  add column if not exists program text not null default 'scouts_bsa'
    check (program in ('scouts_bsa','cubs')),
  add column if not exists rank_code text,
  add column if not exists required boolean not null default false,
  add column if not exists electives_needed integer,
  add column if not exists grade text,
  add column if not exists source_slug text;

create index if not exists idx_adv_items_program on public.advancement_items (program, kind, rank_code);

